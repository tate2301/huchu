// Builds lib/icons/corelith-nav.generated.tsx from the Corelith icon pack.
//
// Only the icons the navigation registry names are written, so the sidebar
// carries about sixty small components rather than the pack's 618. Run after
// changing an `icon:` in lib/nav/registry.ts or updating the pack:
//
//   node scripts/icons/build-corelith.mjs
//
// The pack is design/nav/icons/icons.json (18 grid, two-tone `fill-duo`, the
// second tone at 40%). Brand marks are never in it.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const pack = JSON.parse(fs.readFileSync(path.join(root, "design/nav/icons/icons.json"), "utf8"));
const registry = fs.readFileSync(path.join(root, "lib/nav/registry.ts"), "utf8");

const names = [...new Set([...registry.matchAll(/icon: "([a-z0-9-]+)"/g)].map((m) => m[1]))].sort();
const missing = names.filter((name) => !pack[name]);
if (missing.length) {
  console.error(`Not in the Corelith pack: ${missing.join(", ")}`);
  process.exit(1);
}

const pascal = (name) => name.split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join("");

const components = names
  .map((name) => {
    const inner = pack[name]["fill-duo"];
    return `const ${pascal(name)} = /*#__PURE__*/ icon(\n  <>${inner}</>,\n);`;
  })
  .join("\n\n");

const map = names.map((name) => `  ${JSON.stringify(name)}: ${pascal(name)},`).join("\n");

const out = `/* eslint-disable */
// Generated by scripts/icons/build-corelith.mjs from design/nav/icons/icons.json. Do not edit.
import * as React from "react";

export type CorelithIconProps = React.SVGProps<SVGSVGElement>;
export type CorelithIcon = (props: CorelithIconProps) => React.ReactElement;

function icon(children: React.ReactNode): CorelithIcon {
  return function CorelithGlyph(props) {
    return (
      <svg viewBox="0 0 18 18" fill="currentColor" aria-hidden="true" focusable="false" {...props}>
        {children}
      </svg>
    );
  };
}

${components}

/** The icons the navigation registry names, by their name in the pack. */
export const NAV_ICONS: Record<string, CorelithIcon> = {
${map}
};
`;
fs.mkdirSync(path.join(root, "lib/icons"), { recursive: true });
fs.writeFileSync(path.join(root, "lib/icons/corelith-nav.generated.tsx"), out);
console.log(`${names.length} icons written`);
