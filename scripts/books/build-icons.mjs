/**
 * Corelith UI icons as TypeScript, from the pack in design/books/icons
 * (design/books/spec/icons.md), the way design/core-modules/build/build-icons.py
 * writes components/core/icons.ts.
 *
 *   node scripts/books/build-icons.mjs
 *
 * writes components/books/icons/glyphs.ts (every icon in its four styles, one
 * named export each so the shell's panel only bundles the ones it names) and
 * components/books/icons/labels.ts (which icon goes with which row, from
 * CI_LABEL in design/books/source/ci.mjs). Change the pack or ci.mjs, never the output.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const pack = JSON.parse(readFileSync(join(root, "design/books/icons/dist/icons.json"), "utf8"));
const out = join(root, "components/books/icons");

const ident = (name) => `ci_${name.replace(/-/g, "_")}`;
const names = Object.keys(pack).sort();

const glyphs = [
  "/* Generated by scripts/books/build-icons.mjs from design/books/icons/dist/icons.json. Do not edit. */",
  "",
  'import type { CiGlyph } from "./types";',
  "",
];
for (const name of names) {
  const icon = pack[name];
  glyphs.push(
    `export const ${ident(name)}: CiGlyph = { name: ${JSON.stringify(name)}, outline: ${JSON.stringify(icon.outline)}, "outline-duo": ${JSON.stringify(icon["outline-duo"])}, fill: ${JSON.stringify(icon.fill)}, "fill-duo": ${JSON.stringify(icon["fill-duo"])} };`,
  );
}
glyphs.push("", "/** Every glyph by its pack name. Books pages only: the shell imports glyphs by name. */", "export const CI_GLYPHS = {");
for (const name of names) glyphs.push(`  ${JSON.stringify(name)}: ${ident(name)},`);
glyphs.push("} as const;", "", "export type CiName = keyof typeof CI_GLYPHS;", "");
writeFileSync(join(out, "glyphs.ts"), glyphs.join("\n"));

// CI_LABEL is a single object literal on its own line in ci.mjs.
const ci = readFileSync(join(root, "design/books/source/ci.mjs"), "utf8");
const labelLine = ci.split("\n").find((line) => line.startsWith("const CI_LABEL = "));
const labelMap = JSON.parse(labelLine.slice("const CI_LABEL = ".length).replace(/;\s*$/, ""));
for (const [label, name] of Object.entries(labelMap)) {
  if (!pack[name]) throw new Error(`CI_LABEL names ${name} for ${label}, which the pack does not have.`);
}
const labels = [
  "/* Generated by scripts/books/build-icons.mjs from design/books/source/ci.mjs (CI_LABEL). Do not edit. */",
  "",
  'import type { CiName } from "./glyphs";',
  "",
  "/** The icon every panel row, level, page title and Management row carries, by its label. */",
  "export const CI_LABEL: Record<string, CiName> = {",
  ...Object.entries(labelMap).map(([label, name]) => `  ${JSON.stringify(label)}: ${JSON.stringify(name)},`),
  "};",
  "",
];
writeFileSync(join(out, "labels.ts"), labels.join("\n"));

console.log(`wrote ${relative(root, join(out, "glyphs.ts"))} (${names.length} icons) and labels.ts (${Object.keys(labelMap).length} labels)`);
