export type GlyphName = keyof typeof GLYPHS;

export function Glyph({
  name,
  size,
  className,
  style,
}: {
  name: GlyphName;
  size?: "sm" | "lg";
  className?: string;
  style?: React.CSSProperties;
}) {
  const Icon = GLYPHS[name];
  return <Icon className={cn("i", size === "sm" && "i-sm", size === "lg" && "i-lg", className)} style={style} />;
}
