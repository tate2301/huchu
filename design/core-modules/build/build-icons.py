"""The kit's icons as a TypeScript map, from the board generator's set (tools/boards/ck.py),
so the app draws the glyphs the boards were drawn with.

    python3 design/core-modules/build/build-icons.py

writes components/core/icons.ts. Change ck.py or icons.json, never the output."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'tools', 'boards'))
import ck  # noqa: E402

root = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
names = sorted(k for k, v in ck.IC.items() if v)
lines = ['/* Generated by design/core-modules/build/build-icons.py from tools/boards/ck.py. Do not edit. */',
         '',
         '/** Each icon\'s inner SVG on a 24 grid: filled, as the kit draws them. */',
         'export const ICONS = {']
for k in names:
    lines.append('  %s: %s,' % (json.dumps(k), json.dumps(ck.IC[k])))
lines += ['} as const;', '', 'export type IconName = keyof typeof ICONS;', '']
out = os.path.join(root, 'components', 'core', 'icons.ts')
open(out, 'w').write('\n'.join(lines))
print('wrote', os.path.relpath(out, root), len(names), 'icons')
